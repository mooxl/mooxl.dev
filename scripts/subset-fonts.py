"""Subset the IBM Plex sources in fonts/ into the web fonts the site serves.

Run by hand and commit the output:  uv run scripts/subset-fonts.py

Writes src/assets/fonts/*.woff2 and src/styles/fonts.css. The build embeds the core files in the
inlined CSS (see astro.config.mjs) and content-hashes the extended ones into
/_astro/. Rerun when
- content gains a non-ASCII character that isn't in the core yet. Until then it
  still renders in Plex from the extended file, but it costs an extra download
  and loses kerning with its neighbours; outside Latin-1 and Latin Extended-A
  it falls back to sans-serif,
- the site starts using another weight, italics or OpenType features,
- a source font in fonts/ changes.
"""

from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SOURCES = {400: ROOT / "fonts/Plex-Regular.woff2", 700: ROOT / "fonts/Plex-Bold.woff2"}
FAMILY = "Mooxl Sans"  # IBM Plex is OFL with Reserved Font Name "Plex", so the subsets need another name
FILE = "mooxl-sans"

ASCII = set(range(0x20, 0x7F))
PUNCTUATION = {ord(c) for c in "‘’‚“”„–—…•"}
LATIN = set(range(0xA0, 0x100)) | set(range(0x100, 0x180))  # Latin-1 Supplement, Latin Extended-A
# Browser defaults that exist in Plex; everything else (frac, ss0x, zero, ...) is never turned on.
FEATURES = ["ccmp", "locl", "liga", "kern", "mark"]


def content_chars():
	"""Every non-ASCII character in the site sources, plus case variants for text-transform."""
	chars = set()
	for path in (ROOT / "src").rglob("*"):
		if path.suffix in {".astro", ".json", ".md", ".mdx", ".ts", ".css"}:
			text = path.read_text()
			chars |= {ord(c) for c in text + text.upper() + text.lower() if ord(c) > 0x7E}
	return chars


def make(source, unicodes, out):
	options = subset.Options()
	options.flavor = "woff2"
	options.layout_features = FEATURES
	options.hinting = False
	options.glyph_names = False
	options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
	options.layout_scripts = ["DFLT", "latn"]
	options.drop_tables += ["FFTM"]
	font = subset.load_font(source, options)
	subsetter = subset.Subsetter(options)
	subsetter.populate(unicodes=unicodes)
	subsetter.subset(font)
	for record in font["name"].names:
		value = record.toUnicode()
		renamed = value.replace("IBM Plex Sans", FAMILY).replace("IBMPlexSans", FAMILY.replace(" ", ""))
		if renamed != value:
			record.string = renamed
	assert not any("Plex" in r.toUnicode() for r in font["name"].names if r.nameID in (1, 3, 4, 6, 16, 17))
	subset.save_font(font, out, options)
	return sorted(TTFont(out).getBestCmap())


def unicode_range(codepoints):
	ranges, start = [], None
	for i, cp in enumerate(codepoints):
		if start is None:
			start = cp
		if i + 1 == len(codepoints) or codepoints[i + 1] != cp + 1:
			ranges.append(f"U+{start:X}" if start == cp else f"U+{start:X}-{cp:X}")
			start = None
	return ", ".join(ranges)


def main():
	used = content_chars()
	# Characters from different files can't kern with each other (e.g. "Kö"), so every character
	# the content uses goes into the core. The extended file only covers characters added later.
	core = ASCII | PUNCTUATION | used
	extended = (LATIN | used) - core
	out_dir = ROOT / "src/assets/fonts"
	out_dir.mkdir(parents=True, exist_ok=True)
	for old in out_dir.glob(f"{FILE}-*.woff2"):
		old.unlink()
	css = [f"/* Generated by scripts/subset-fonts.py. Do not edit by hand. */"]
	for weight, source in SOURCES.items():
		cmap = set(TTFont(source).getBestCmap())
		missing = sorted(c for c in used - cmap)
		if missing:
			print(f"{weight}: not in source font, left to the fallback font: {''.join(map(chr, missing))}")
		for part, unicodes in (("core", core), ("ext", extended)):
			if not unicodes & cmap:
				continue  # fontTools would write a font without a cmap
			out = out_dir / f"{FILE}-{weight}-{part}.woff2"
			codepoints = make(source, sorted(unicodes & cmap), out)
			css.append(
				"@font-face {\n"
				f'\tfont-family: "{FAMILY}";\n'
				f"\tfont-weight: {weight};\n"
				"\tfont-display: block;\n"  # wait for the font instead of reflowing from a fallback
				f'\tsrc: url(../assets/fonts/{out.name}) format("woff2");\n'
				f"\tunicode-range: {unicode_range(codepoints)};\n"
				"}"
			)
			print(f"{out.relative_to(ROOT)}: {out.stat().st_size} bytes, {len(codepoints)} characters")
	(ROOT / "src/styles/fonts.css").write_text("\n".join(css) + "\n")


main()
